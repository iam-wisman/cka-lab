#!/usr/bin/env python3
"""Generate lab/labs/*/cleanup.sh and lab/exams/*/cleanup.sh from the bash blocks
in each task's "## Cleaning up" section, so the docs and `lab cleanup` never drift.

Blocks that only take snapshots are skipped (`lab cleanup` must never stop the
nodes). Deletions get --ignore-not-found so a cleanup can be run twice.
"""
import glob, os, re, stat

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lab")

def blocks(md, heading):
    if heading not in md:
        return []
    sec = md.split(heading, 1)[1]
    sec = re.split(r"\n## ", sec, maxsplit=1)[0]
    return re.findall(r"```bash\n(.*?)```", sec, re.S)

def harden(line):
    s = line.rstrip()
    if re.match(r"^\s*kubectl\b.*\bdelete\b", s) and "--ignore-not-found" not in s and "| kubectl" not in s:
        code, _, comment = s.partition("  #")
        s = code.rstrip() + " --ignore-not-found" + ("  #" + comment if comment else "")
    if re.match(r"^\s*helm uninstall\b", s) and "--ignore-not-found" not in s:
        s += " --ignore-not-found"
    if re.match(r"^\s*kubectl taint\b.*-\s*(#.*)?$", s):
        code, _, comment = s.partition("  #")
        s = code.rstrip() + " 2>/dev/null || true" + ("  #" + comment if comment else "")
    return s

HDR = """#!/bin/bash
# Generated by tools/gen-cleanup.py from the "Cleaning up" section of {src}.
# Edit that section, not this file. Runs as student on jump via `lab cleanup`.
set -uo pipefail
"""

def write(dirpath, src_name, bodies):
    path = os.path.join(dirpath, "cleanup.sh")
    useful = [b for b in bodies if "lab snapshot" not in b]
    if not useful:
        if os.path.exists(path):
            os.remove(path)
        return 0
    body = "\n".join("\n".join(harden(l) for l in b.rstrip("\n").splitlines()) for b in useful) + "\n"
    hdr = HDR.format(src=src_name)
    if "{{" in body:   # randomised values: {{KEY}} in the docs, ${KEY} from this attempt's params
        body = re.sub(r"\{\{([A-Z_][A-Z0-9_]*)\}\}", r"${\1}", body)
        hdr = hdr.replace("set -uo pipefail\n", 'source "$LAB_HOME/lib/common.sh"   # loads this attempt\'s values (GRADE_ID)\nset -uo pipefail\n')
    text = hdr + body
    open(path, "w").write(text)
    os.chmod(path, os.stat(path).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return 1

n = 0
for d in sorted(glob.glob(os.path.join(root, "labs", "[0-9][0-9]-*"))):
    md = open(os.path.join(d, "task.md")).read()
    n += write(d, "task.md", blocks(md, "## Cleaning up"))
for d in sorted(glob.glob(os.path.join(root, "exams", "[0-9]*"))):
    md = open(os.path.join(d, "README.md")).read()
    bs = [b for b in blocks(md, "## Cleaning up") if "lab reset" not in b]
    n += write(d, "README.md", bs)
print(f"{n} cleanup scripts written")
